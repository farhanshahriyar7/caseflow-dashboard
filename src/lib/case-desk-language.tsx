export function translateCaseDeskCopy(language: CaseDeskLanguage, copy: string): string {
  return language === "bn" ? (bengaliCopy[copy] ?? copy) : copy;
}

type LanguageContextValue = {
  language: CaseDeskLanguage;
  setLanguage: (language: CaseDeskLanguage) => void;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function CaseDeskLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<CaseDeskLanguage>(DEFAULT_CASE_DESK_LANGUAGE);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage }}>
      {children}
    </LanguageContext.Provider>
  );
}

